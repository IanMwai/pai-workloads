#!/usr/bin/env python3
"""Drive an OpenAI-compatible inference server with Poisson-process arrivals.

The arrival process is a nonhomogeneous Poisson process (NHPP) whose rate
lambda(t) follows either a diurnal sinusoid or the per-minute request counts of
one day of a real trace (Azure LLM inference trace CSV: TIMESTAMP,
ContextTokens, GeneratedTokens).  Arrivals are generated by Lewis-Shedler
thinning, then fired at the server on schedule; requests that find the server
busy simply queue, as they would in production.

Typical use, bracketed by a pai run so power and requests share one clock:

    CUDA_VISIBLE_DEVICES=1 vllm serve meta-llama/Llama-3.1-8B-Instruct \
        --dtype half --max-model-len 4096 --port 8001        # in another shell

    pai hardware --name day_inference -- \
        nhpp-load --url http://127.0.0.1:8001/v1 \
            --profile sinusoid --hours 24 --compress 12

`--compress 12` replays a 24 h shape in 2 h (all rates x12).  `--dry-run`
prints the planned arrivals per hour without a server.  Every request is
logged as one JSON line (planned/sent/done times, tokens, latency) to
$PAI_RUN_DIR/workload/ when pai exports it, so the log is archived with the run.
Standard library only.
"""
from __future__ import annotations

import argparse
import asyncio
import csv
import datetime as dt
import json
import math
import os
import random
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

WORDS = ("data center power model energy request token batch latency server cache "
         "memory kernel thermal cooling rack load queue sample voltage current shunt "
         "network gradient tensor matrix vector schedule arrival process poisson").split()


# --------------------------------------------------------------------------- rate profiles

def sinusoid_profile(base: float, peak: float, peak_hour: float):
    """lambda(t) in requests/s, t in seconds of experiment time; a 24 h cosine."""
    def lam(t: float) -> float:
        h = (t / 3600.0) % 24.0
        return base + (peak - base) * (1.0 + math.cos(2 * math.pi * (h - peak_hour) / 24.0)) / 2.0
    return lam


def _parse_ts(s: str) -> dt.datetime:
    s = s.strip().replace("T", " ")
    if "." in s:  # Azure traces carry 7 fractional digits; fromisoformat wants <= 6
        head, frac = s.split(".", 1)
        s = f"{head}.{frac[:6]}"
    return dt.datetime.fromisoformat(s)


def load_trace(path: Path, day: int, rate_scale: float, bin_sec: int = 60):
    """Per-bin lambda(t) and (prompt, output) token pairs for one day of a trace."""
    rows = []
    with open(path, newline="") as fh:
        reader = csv.DictReader(fh)
        cols = {c.lower(): c for c in reader.fieldnames or []}
        ts_col = cols.get("timestamp")
        in_col = cols.get("contexttokens") or cols.get("prompt_tokens") or cols.get("input_tokens")
        out_col = cols.get("generatedtokens") or cols.get("completion_tokens") or cols.get("output_tokens")
        if not ts_col:
            sys.exit(f"{path}: no TIMESTAMP column (have {reader.fieldnames})")
        for r in reader:
            rows.append((_parse_ts(r[ts_col]),
                         int(float(r[in_col])) if in_col and r[in_col] else None,
                         int(float(r[out_col])) if out_col and r[out_col] else None))
    rows.sort(key=lambda r: r[0])
    t0 = rows[0][0].replace(hour=0, minute=0, second=0, microsecond=0) + dt.timedelta(days=day)
    t1 = t0 + dt.timedelta(days=1)
    day_rows = [r for r in rows if t0 <= r[0] < t1]
    if not day_rows:
        sys.exit(f"{path}: no rows on day {day} ({t0.date()}); trace spans "
                 f"{rows[0][0].date()} .. {rows[-1][0].date()}")
    nbins = 86400 // bin_sec
    counts = [0] * nbins
    for ts, _, _ in day_rows:
        counts[int((ts - t0).total_seconds()) // bin_sec] += 1
    rates = [c / bin_sec * rate_scale for c in counts]

    def lam(t: float) -> float:
        return rates[min(int(t // bin_sec), nbins - 1)]

    tokens = [(i, o) for _, i, o in day_rows if i and o]
    return lam, tokens, str(t0.date()), len(day_rows)


# --------------------------------------------------------------------------- arrivals

def thinning(lam, horizon_s: float, rng: random.Random, grid_s: float = 60.0) -> list[float]:
    """Lewis-Shedler thinning: arrival times (experiment seconds) on [0, horizon)."""
    lam_max = max(lam(t) for t in frange(0.0, horizon_s, grid_s)) * 1.001
    if lam_max <= 0:
        return []
    out, t = [], 0.0
    while True:
        t += rng.expovariate(lam_max)
        if t >= horizon_s:
            return out
        if rng.random() * lam_max <= lam(t):
            out.append(t)


def frange(a: float, b: float, step: float):
    x = a
    while x < b:
        yield x
        x += step


# --------------------------------------------------------------------------- requests

def make_prompt(n_tokens: int, rng: random.Random) -> str:
    # ~1.3 tokens per short English word; random words defeat prefix caching
    return " ".join(rng.choice(WORDS) for _ in range(max(1, int(n_tokens / 1.3))))


def post_json(url: str, payload: dict, timeout: float) -> dict:
    req = urllib.request.Request(url, data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"}, method="POST")
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read())


async def fire(i: int, planned: float, start_wall: float, args, tokens, rng: random.Random,
               sem: asyncio.Semaphore, log, stats: dict):
    if tokens:
        p_tok, o_tok = rng.choice(tokens)
        o_tok = max(1, min(o_tok, args.max_tokens))
    else:
        p_tok, o_tok = args.prompt_tokens, args.max_tokens
    payload = {
        "model": args.model,
        "messages": [{"role": "user", "content": make_prompt(p_tok, rng)}],
        "max_tokens": o_tok,
        "ignore_eos": True,  # vLLM: generate exactly max_tokens, like the trace said
        "stream": False,
    }
    rec = {"id": i, "planned_s": round(planned, 4), "prompt_tokens_req": p_tok, "max_tokens": o_tok}
    async with sem:
        t_send = time.time()
        rec["queued_s"] = round(t_send - (start_wall + planned), 4)
        rec["sent"] = dt.datetime.fromtimestamp(t_send, dt.timezone.utc).isoformat()
        try:
            data = await asyncio.to_thread(post_json, f"{args.url.rstrip('/')}/chat/completions",
                                           payload, args.timeout)
            usage = data.get("usage", {})
            rec.update(status="ok", prompt_tokens=usage.get("prompt_tokens"),
                       completion_tokens=usage.get("completion_tokens"))
            stats["ok"] += 1
        except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, OSError, ValueError) as exc:
            rec.update(status="error", error=str(exc)[:200])
            stats["err"] += 1
        t_done = time.time()
        rec["done"] = dt.datetime.fromtimestamp(t_done, dt.timezone.utc).isoformat()
        rec["latency_s"] = round(t_done - t_send, 4)
    log.write(json.dumps(rec) + "\n")
    log.flush()


async def run(args, lam, tokens, arrivals: list[float]) -> int:
    rng = random.Random(args.seed + 1)
    sem = asyncio.Semaphore(args.max_inflight)
    stats = {"ok": 0, "err": 0}
    log_path = args.log or default_log_path()
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(log_path, "w") as log:
        header = {"config": {k: (str(v) if isinstance(v, Path) else v) for k, v in vars(args).items()},
                  "n_arrivals": len(arrivals), "started": dt.datetime.now(dt.timezone.utc).isoformat(),
                  "rate_per_min": [round(lam(t * 60 * args.compress) * args.compress, 5)
                                   for t in range(int(args.hours * 60 / args.compress))]}
        log.write(json.dumps({"header": header}) + "\n")
        print(f"[nhpp] {len(arrivals)} requests over {args.hours / args.compress:.2f} h wall "
              f"({args.hours} h experiment time, x{args.compress}); log: {log_path}")
        start_wall = time.time()
        tasks = []
        for i, planned in enumerate(arrivals):
            delay = start_wall + planned - time.time()
            if delay > 0:
                await asyncio.sleep(delay)
            tasks.append(asyncio.create_task(fire(i, planned, start_wall, args, tokens, rng, sem, log, stats)))
            if i % 100 == 0 and i:
                print(f"[nhpp] {i}/{len(arrivals)} sent, {stats['ok']} ok, {stats['err']} errors, "
                      f"{len([t for t in tasks if not t.done()])} in flight  ({time.strftime('%H:%M:%S')})")
        await asyncio.gather(*tasks)
    print(f"[nhpp] done: {stats['ok']} ok, {stats['err']} errors; log: {log_path}")
    return 0 if stats["err"] == 0 else 2


def default_log_path() -> Path:
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    run_dir = os.environ.get("PAI_RUN_DIR")
    base = Path(run_dir) / "workload" if run_dir else Path.cwd()
    return base / f"nhpp_requests_{stamp}.jsonl"


# --------------------------------------------------------------------------- main

def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--url", default="http://127.0.0.1:8001/v1", help="OpenAI-compatible base URL")
    p.add_argument("--model", default="default", help="model name as the server reports it")
    src = p.add_mutually_exclusive_group()
    src.add_argument("--profile", choices=["sinusoid"], default="sinusoid")
    src.add_argument("--trace", type=Path, help="Azure-style trace CSV (TIMESTAMP, ContextTokens, GeneratedTokens)")
    p.add_argument("--day", type=int, default=0, help="which day of the trace to replay (0 = first)")
    p.add_argument("--rate-scale", type=float, default=1.0, help="multiply the trace's rate (before --compress)")
    p.add_argument("--hours", type=float, default=24.0, help="experiment-time length")
    p.add_argument("--compress", type=float, default=1.0, help="time compression: 24 means a day runs in 1 h")
    p.add_argument("--base-rate", type=float, default=0.05, help="sinusoid: night rate, requests/s")
    p.add_argument("--peak-rate", type=float, default=0.5, help="sinusoid: peak rate, requests/s")
    p.add_argument("--peak-hour", type=float, default=14.0, help="sinusoid: hour of the peak")
    p.add_argument("--prompt-tokens", type=int, default=256, help="prompt length when no trace")
    p.add_argument("--max-tokens", type=int, default=128, help="output length (cap when using a trace)")
    p.add_argument("--max-inflight", type=int, default=64, help="client-side concurrency cap")
    p.add_argument("--timeout", type=float, default=600.0)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--log", type=Path, help="JSONL request log (default: $PAI_RUN_DIR/workload/...)")
    p.add_argument("--dry-run", action="store_true", help="print planned arrivals per hour and exit")
    return p


def plan(args):
    rng = random.Random(args.seed)
    tokens = None
    if args.trace:
        lam_exp, tokens, date, n = load_trace(args.trace, args.day, args.rate_scale)
        print(f"[nhpp] trace {args.trace.name}: day {args.day} = {date}, {n} requests")
    else:
        lam_exp = sinusoid_profile(args.base_rate, args.peak_rate, args.peak_hour)
    # experiment time -> wall time: lambda_wall(t_wall) = C * lambda_exp(C * t_wall)
    c = args.compress

    def lam_wall(t: float) -> float:
        return c * lam_exp(c * t)

    arrivals = thinning(lam_wall, args.hours * 3600.0 / c, rng, grid_s=60.0 / c)
    return lam_exp, tokens, arrivals


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    lam_exp, tokens, arrivals = plan(args)
    if args.dry_run:
        per_hour = [0] * int(math.ceil(args.hours))
        for t in arrivals:
            per_hour[min(int(t * args.compress // 3600), len(per_hour) - 1)] += 1
        print(f"[nhpp] {len(arrivals)} arrivals over {args.hours} h experiment time "
              f"({args.hours / args.compress:.2f} h wall at x{args.compress})")
        for h, n in enumerate(per_hour):
            print(f"  hour {h:2d}: {n:6d}  {'#' * (60 * n // max(1, max(per_hour)))}")
        return 0
    return asyncio.run(run(args, lam_exp, tokens, arrivals))


if __name__ == "__main__":
    sys.exit(main())
